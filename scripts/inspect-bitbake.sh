#!/usr/bin/env bash
# Record what BitBake actually resolved for this build: layers, revisions and
# the key variables of a recipe. Writes manifests/build-manifest.txt, which is
# the traceability record attached to a validation report.
#
#   scripts/inspect-bitbake.sh [recipe]        (default recipe: gnss-sdr)
#
# The bitbake commands run inside the kas container; do not run them on the
# bare host.
set -euo pipefail
# shellcheck source=scripts/lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

require_linux
recipe="${1:-gnss-sdr}"
out="$REPO_DIR/manifests/build-manifest.txt"
kas_file="kas/uno-q-gnss-sdr.yml"

cd "$REPO_DIR"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

info "Querying BitBake for layers and for recipe '$recipe'"
kas_container shell "$kas_file" -c "
    set -e
    echo '### bitbake-layers show-layers'
    bitbake-layers show-layers
    echo
    echo '### bitbake-layers show-recipes $recipe'
    bitbake-layers show-recipes '$recipe'
    echo
    echo '### bitbake -e $recipe (selected variables)'
    bitbake -e '$recipe' | grep -E '^(PN|PV|SRCREV|SRC_URI|LICENSE|DEPENDS|RDEPENDS:[^=]*|PACKAGECONFIG|EXTRA_OECMAKE|TUNE_FEATURES|TUNE_CCARGS|TARGET_ARCH|TARGET_SYS|DISTRO|DISTRO_VERSION|MACHINE|PREFERRED_PROVIDER_virtual/kernel)='
    echo
    echo '### bitbake -e (global)'
    bitbake -e | grep -E '^(DISTRO_FEATURES|MACHINE_FEATURES|IMAGE_FSTYPES|INIT_MANAGER|TCLIBC|GCCVERSION|SDK_VERSION|KERNEL_DEVICETREE|SERIAL_CONSOLES)='
" > "$tmp" 2>&1 || { cat "$tmp" >&2; die "bitbake query failed."; }

{
    echo "# Build manifest - generated by scripts/inspect-bitbake.sh"
    echo "# Date (UTC): $(date -u +%Y-%m-%dT%H:%M:%SZ)"
    echo "# Host: $(uname -srm)"
    echo "# This repository: $(git -C "$REPO_DIR" rev-parse HEAD 2> /dev/null || echo unknown)$(git -C "$REPO_DIR" diff --quiet 2> /dev/null || echo ' (with uncommitted changes)')"
    echo
    echo "### Layer checkouts"
    for dir in "$KAS_WORK_DIR"/*/; do
        [ -d "$dir/.git" ] || continue
        printf '%-24s %s\n' "$(basename "$dir")" "$(git -C "$dir" rev-parse HEAD)"
    done
    echo
    cat "$tmp"
} > "$out"

info "Wrote $out"
grep -E '^(SRCREV|TUNE_FEATURES|PACKAGECONFIG|DEPENDS)=' "$out" || true
